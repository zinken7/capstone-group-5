-- FR-55 automated evidence check (docs/verification/fr55-design.md §5).
--
-- PARKED: this file lives outside backend/migrations/ on purpose. It assumes
-- the ERD's contribution entities exist — the revision table and the
-- evidence_type enum (docs/database/ERD.md) — which migration 002 is expected
-- to provide. Move it into backend/migrations/ and renumber once that
-- sequencing is decided; until then the pipeline runs without a database and
-- store.ts writes through a pluggable interface.
--
-- All three tables are append-only: a re-check after an edit inserts a new
-- report; nothing here is ever updated, and this code never writes
-- deployment.verification_status (design R3). Feature-internal vocabularies
-- are TEXT with CHECK rather than enums, because they are expected to move
-- with the evaluation (design §7) and are read by no other feature.

CREATE TABLE verification_report (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  deployment_id BIGINT NOT NULL REFERENCES deployment(id),
  -- The submission snapshot that was checked. The report is evidence about
  -- a revision, not about the deployment's current state.
  revision_id BIGINT NOT NULL REFERENCES revision(id),

  -- 'passed', or the first stage-0 rule that failed (design §6 stage 0).
  -- The honeypot is an API concern and never reaches this pipeline.
  spam_gate_result TEXT NOT NULL CHECK (spam_gate_result IN
    ('passed', 'no_url', 'unresolvable_url', 'junk_domain', 'links_only')),

  recommendation TEXT NOT NULL CHECK (recommendation IN
    ('verify', 'request_more_evidence', 'reject')),
  -- The aggregation rule that fired, in words (design §6 stage 5).
  recommendation_basis TEXT NOT NULL,

  -- Field verdicts as computed at generation time, keyed by field name, so
  -- the review panel shows what this report said even after the aggregation
  -- rules change in code.
  field_verdicts JSONB NOT NULL DEFAULT '{}',

  -- Reproducibility tuple (design §8): which models and which prompt
  -- produced this report. Null when the gate rejected before any model ran.
  model_name TEXT,
  prompt_version TEXT,

  generated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


CREATE TABLE fetched_source (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id BIGINT NOT NULL REFERENCES verification_report(id),

  url TEXT NOT NULL,
  -- Wayback snapshot used when the live fetch failed (design §6 stage 1).
  archived_url TEXT,
  -- Status of the live attempt; null when the request itself failed.
  http_status INTEGER,
  published_date DATE,
  -- Same vocabulary as evidence.source_type; null when there was no page to
  -- classify.
  source_class evidence_type,

  -- D5: the text as it was when checked, not only its hash. Pages change
  -- and vanish; the reviewer must see what the verdicts cite. Claim quote
  -- offsets index into exactly this string.
  extracted_text TEXT,
  text_sha256 TEXT,
  fetched_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

  -- A hash without its text (or text without its hash) would break the
  -- reproducibility definition in design §8.
  CONSTRAINT fetched_source_text_hash_paired CHECK (
    (extracted_text IS NULL) = (text_sha256 IS NULL)
  )
);


CREATE TABLE verification_claim (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id BIGINT NOT NULL REFERENCES verification_report(id),

  field TEXT NOT NULL CHECK (field IN
    ('site', 'company_role', 'machine', 'technology', 'quantity', 'commissioning')),
  -- Which instance of the field the claim is about, when a submission
  -- carries several — for company_role, the company and role (for example
  -- 'rio-tinto:operator'). Empty for single-instance fields, so the unique
  -- key below holds.
  subject TEXT NOT NULL DEFAULT '',
  -- Sub-fact names come from the table in design §6.1, which is versioned
  -- in code and still to be confirmed with the client; deliberately not
  -- CHECKed here.
  sub_fact TEXT NOT NULL,
  required BOOLEAN NOT NULL,
  hypothesis TEXT NOT NULL,

  -- The raw verifier verdict (design §4.4). D3 and the field-level rules
  -- are applied in aggregation, not stored per claim.
  verdict TEXT NOT NULL CHECK (verdict IN
    ('supported', 'contradicted', 'insufficient')),

  -- The cited span: absolute character offsets into the stored
  -- extracted_text of the fetched source, so the review panel can open the
  -- page as it was and highlight the quote. quote_end <= length of that
  -- text is cross-row and enforced by store.ts before insert.
  source_id BIGINT REFERENCES fetched_source(id),
  quote_start INTEGER,
  quote_end INTEGER,

  -- NLI entailment score when one was computed; which branch of design §4.2
  -- produced the verdict; the reviewer note from the LLM path. path is null
  -- when retrieval found no candidates and stage 4 never ran.
  score NUMERIC,
  path TEXT CHECK (path IN ('nli', 'llm')),
  note TEXT,

  UNIQUE (report_id, field, subject, sub_fact),

  -- R1: a verdict is only as good as the span it cites. supported and
  -- contradicted must cite one; insufficient need not.
  CONSTRAINT verification_claim_span_cited CHECK (
    verdict = 'insufficient'
    OR (source_id IS NOT NULL AND quote_start IS NOT NULL AND quote_end IS NOT NULL)
  ),
  CONSTRAINT verification_claim_offsets_paired CHECK (
    (quote_start IS NULL) = (quote_end IS NULL)
  ),
  CONSTRAINT verification_claim_span_ordered CHECK (
    quote_start IS NULL OR quote_end > quote_start
  )
);


-- Panel reads "latest report for this revision"; the eval export (design
-- §7.3) walks reports per deployment.
CREATE INDEX verification_report_deployment_id_idx
  ON verification_report(deployment_id);

CREATE INDEX verification_report_revision_generated_idx
  ON verification_report(revision_id, generated_at);

CREATE INDEX verification_claim_report_id_idx
  ON verification_claim(report_id);

CREATE INDEX fetched_source_report_id_idx
  ON fetched_source(report_id);


-- Append-only, enforced rather than promised (design §6 stage 6).
CREATE FUNCTION forbid_change() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION '% is append-only', TG_TABLE_NAME;
END;
$$;

CREATE TRIGGER verification_report_append_only
  BEFORE UPDATE OR DELETE ON verification_report
  FOR EACH ROW EXECUTE FUNCTION forbid_change();

CREATE TRIGGER verification_claim_append_only
  BEFORE UPDATE OR DELETE ON verification_claim
  FOR EACH ROW EXECUTE FUNCTION forbid_change();

CREATE TRIGGER fetched_source_append_only
  BEFORE UPDATE OR DELETE ON fetched_source
  FOR EACH ROW EXECUTE FUNCTION forbid_change();
