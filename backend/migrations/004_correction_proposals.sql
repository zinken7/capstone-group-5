-- Corrections to verified records become proposals (#114, decided in #62).
-- A public correction to a verified deployment is stored here and leaves the
-- live row untouched, so the record stays public until an administrator
-- approves the change. Corrections to records that are not verified still
-- apply directly, as before. No BEGIN/COMMIT: the runner wraps this file.
SET LOCAL search_path = public, pg_catalog;

CREATE TYPE correction_status AS ENUM ('pending', 'approved', 'rejected', 'needs_changes');

CREATE TABLE deployment_correction (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  deployment_id BIGINT NOT NULL REFERENCES deployment(id),
  contributor_id BIGINT REFERENCES contributor(id),
  -- Changed fields only, keyed by API field name. base_values holds the same
  -- fields as they were when the correction was submitted, so a reviewer can
  -- see when the record has changed since.
  proposed_values JSONB NOT NULL,
  base_values JSONB NOT NULL,
  evidence_urls TEXT[] NOT NULL,
  change_note TEXT,
  status correction_status NOT NULL DEFAULT 'pending',
  submitted_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT deployment_correction_values_are_objects CHECK (
    jsonb_typeof(proposed_values) = 'object' AND jsonb_typeof(base_values) = 'object'
  ),
  CONSTRAINT deployment_correction_changes_something CHECK (
    proposed_values <> '{}'::jsonb OR cardinality(evidence_urls) > 0
  ),
  -- Target of the composite foreign key from verification_review below
  CONSTRAINT deployment_correction_id_deployment_unique UNIQUE (id, deployment_id)
);

CREATE INDEX deployment_correction_deployment_idx
  ON deployment_correction(deployment_id, submitted_at);
CREATE INDEX deployment_correction_pending_idx
  ON deployment_correction(submitted_at) WHERE status = 'pending';

-- A proposal is never edited or removed: only its status moves, once, from
-- pending to a decision. The decision itself is the verification_review row.
CREATE FUNCTION restrict_correction_update() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF OLD.status <> 'pending' THEN
    RAISE EXCEPTION 'deployment_correction % has already been decided', OLD.id;
  END IF;
  IF (NEW.deployment_id, NEW.contributor_id, NEW.proposed_values, NEW.base_values,
      NEW.evidence_urls, NEW.change_note, NEW.submitted_at)
     IS DISTINCT FROM
     (OLD.deployment_id, OLD.contributor_id, OLD.proposed_values, OLD.base_values,
      OLD.evidence_urls, OLD.change_note, OLD.submitted_at) THEN
    RAISE EXCEPTION 'deployment_correction only allows its status to change';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER deployment_correction_restrict_update
  BEFORE UPDATE ON deployment_correction
  FOR EACH ROW EXECUTE FUNCTION restrict_correction_update();
CREATE TRIGGER deployment_correction_no_delete
  BEFORE DELETE ON deployment_correction
  FOR EACH ROW EXECUTE FUNCTION reject_history_mutation();
CREATE TRIGGER deployment_correction_no_truncate
  BEFORE TRUNCATE ON deployment_correction
  FOR EACH STATEMENT EXECUTE FUNCTION reject_history_mutation();

-- A review either decides the record itself (correction_id NULL) or one of
-- its corrections. The composite key keeps the two on the same deployment.
ALTER TABLE verification_review
  ADD COLUMN correction_id BIGINT,
  ADD CONSTRAINT verification_review_correction_same_deployment_fkey
    FOREIGN KEY (correction_id, deployment_id)
    REFERENCES deployment_correction(id, deployment_id);
CREATE INDEX verification_review_correction_idx
  ON verification_review(correction_id) WHERE correction_id IS NOT NULL;

COMMENT ON TABLE deployment_correction IS
  'Public corrections to verified deployments, waiting for or holding an administrator decision. Approval applies proposed_values to the deployment and writes an update revision.';
