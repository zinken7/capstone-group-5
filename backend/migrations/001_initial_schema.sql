CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TYPE company_role AS ENUM (
  'owner', 'operator', 'contractor'
);

CREATE TYPE site_status AS ENUM (
  'operating', 'commissioning'
);

CREATE TYPE machine_type AS ENUM (
  'haul_truck',
  'lhd',
  'loader',
  'dozer',
  'excavator',
  'drill',
  'scaler',
  'shotcrete_machine',
  'other'
);

CREATE TYPE automation_level AS ENUM (
  'line_of_sight_remote',
  'teleremote',
  'semi_autonomous',
  'autonomous'
);

CREATE TYPE mining_environment AS ENUM (
  'surface', 'underground', 'both'
);

CREATE TYPE deployment_status AS ENUM (
  'announced',
  'commissioning',
  'operational',
  'decommissioned'
);

CREATE TYPE verification_status AS ENUM (
  'unverified',
  'pending_review',
  'verified',
  'rejected'
);


CREATE TABLE company (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  country_code TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE region (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  country_code TEXT NOT NULL,

  UNIQUE (name, country_code),
  UNIQUE (id, country_code)
);

CREATE TABLE site (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  country_code TEXT NOT NULL,
  region_id BIGINT,
  commodity TEXT,
  mine_status site_status,
  point_4326 geometry(Point, 4326) NOT NULL,

  FOREIGN KEY (region_id, country_code)
    REFERENCES region(id, country_code)
);

CREATE TABLE site_company_role (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_id BIGINT NOT NULL REFERENCES site(id),
  company_id BIGINT NOT NULL REFERENCES company(id),
  role company_role NOT NULL,

  UNIQUE (site_id, company_id, role)
);

CREATE TABLE machine_model (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  manufacturer_id BIGINT NOT NULL REFERENCES company(id),
  model_name TEXT,
  machine_type machine_type NOT NULL,
  size_class TEXT,
  max_payload_tonnes NUMERIC,
  operating_weight_tonnes NUMERIC
);

CREATE UNIQUE INDEX machine_model_manufacturer_model_unique
  ON machine_model(manufacturer_id, model_name)
  WHERE model_name IS NOT NULL;


CREATE TABLE technology_product (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  supplier_id BIGINT NOT NULL REFERENCES company(id),
  product_name TEXT NOT NULL,
  vendor_term TEXT,
  automation_level automation_level,
  level_basis TEXT
);


CREATE TABLE deployment (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  site_id BIGINT NOT NULL REFERENCES site(id),
  machine_model_id BIGINT NOT NULL REFERENCES machine_model(id),
  technology_product_id BIGINT REFERENCES technology_product(id),

  quantity INTEGER NOT NULL CHECK (quantity > 0),
  environment mining_environment,
  commissioning_date DATE,
  status deployment_status,
  verification_status verification_status NOT NULL DEFAULT 'unverified',

  valid_from DATE,
  valid_to DATE,

  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

  CHECK (
    valid_to IS NULL
    OR valid_from IS NULL
    OR valid_to >= valid_from
  )
);


CREATE INDEX deployment_site_id_idx
  ON deployment(site_id);

CREATE INDEX deployment_machine_model_id_idx
  ON deployment(machine_model_id);

CREATE INDEX deployment_technology_product_id_idx
  ON deployment(technology_product_id);

CREATE INDEX deployment_verification_status_idx
  ON deployment(verification_status);

CREATE INDEX deployment_status_idx
  ON deployment(status);

CREATE INDEX deployment_commissioning_date_idx
  ON deployment(commissioning_date);

CREATE INDEX site_country_code_idx
  ON site(country_code);

CREATE INDEX site_region_id_idx
  ON site(region_id);

CREATE INDEX site_point_4326_gist_idx
  ON site USING GIST(point_4326);