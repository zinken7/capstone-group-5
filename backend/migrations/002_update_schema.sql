-- Block writes while checking and replacing the enum types.
LOCK TABLE company, region, site, site_company_role, machine_model,
  technology_product, deployment IN ACCESS EXCLUSIVE MODE;

DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM technology_product
    WHERE automation_level::text = 'line_of_sight_remote'
  ) THEN
    RAISE EXCEPTION 'Legacy line_of_sight_remote values remain in technology_product. Resolve explicitly before migration; no automatic reclassification is performed.';
  END IF;
  -- The old migration has no evidence table. Do not silently downgrade
  -- existing verified deployments or invent evidence for them.
  IF EXISTS (SELECT 1 FROM deployment WHERE verification_status = 'verified') THEN
    RAISE EXCEPTION 'Existing verified deployments have no evidence in the supplied old schema. Resolve their verification state/evidence migration before applying this upgrade.';
  END IF;
END $$;

