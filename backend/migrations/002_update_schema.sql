-- Only an active admin can create a new review. Deactivating an admin later
-- leaves their historical decisions intact. FOR SHARE serialises deactivation
-- against review creation.
CREATE FUNCTION require_active_review_admin() RETURNS trigger
LANGUAGE plpgsql SET search_path = public, pg_catalog AS $$
DECLARE
  is_active BOOLEAN;
BEGIN
  SELECT active INTO is_active FROM admin_user
    WHERE id = NEW.admin_user_id FOR SHARE;
  IF is_active IS DISTINCT FROM TRUE THEN
    RAISE EXCEPTION 'Verification review requires an active administrator';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER verification_review_active_admin
  BEFORE INSERT ON verification_review
  FOR EACH ROW EXECUTE FUNCTION require_active_review_admin();

CREATE FUNCTION reject_history_mutation() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION '% is append-only; % is forbidden', TG_TABLE_NAME, TG_OP;
END;
$$;
CREATE TRIGGER verification_review_append_only
  BEFORE UPDATE OR DELETE ON verification_review
  FOR EACH ROW EXECUTE FUNCTION reject_history_mutation();
CREATE TRIGGER revision_append_only
  BEFORE UPDATE OR DELETE ON revision
  FOR EACH ROW EXECUTE FUNCTION reject_history_mutation();
CREATE TRIGGER verification_review_no_truncate
  BEFORE TRUNCATE ON verification_review
  FOR EACH STATEMENT EXECUTE FUNCTION reject_history_mutation();
CREATE TRIGGER revision_no_truncate
  BEFORE TRUNCATE ON revision
  FOR EACH STATEMENT EXECUTE FUNCTION reject_history_mutation();

-- Serialise evidence mutations on their deployment row. This prevents two
-- concurrent evidence deletions from each observing the other's last record.
CREATE FUNCTION lock_evidence_deployments() RETURNS trigger
LANGUAGE plpgsql SET search_path = public, pg_catalog AS $$
DECLARE
  old_id BIGINT;
  new_id BIGINT;
BEGIN
  IF TG_OP <> 'INSERT' THEN old_id := OLD.deployment_id; END IF;
  IF TG_OP <> 'DELETE' THEN new_id := NEW.deployment_id; END IF;
  PERFORM id FROM deployment WHERE id IN (old_id, new_id)
    ORDER BY id FOR UPDATE;
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER evidence_lock_deployments
  BEFORE INSERT OR UPDATE OR DELETE ON evidence
  FOR EACH ROW EXECUTE FUNCTION lock_evidence_deployments();

-- Check the FINAL state at transaction end: evidence and verification may
-- be changed in either order within one transaction.
CREATE FUNCTION enforce_verified_evidence() RETURNS trigger
LANGUAGE plpgsql SET search_path = public, pg_catalog AS $$
DECLARE
  old_id BIGINT;
  new_id BIGINT;
BEGIN
  IF TG_TABLE_NAME = 'deployment' THEN
    IF TG_OP <> 'INSERT' THEN old_id := OLD.id; END IF;
    IF TG_OP <> 'DELETE' THEN new_id := NEW.id; END IF;
  ELSE
    IF TG_OP <> 'INSERT' THEN old_id := OLD.deployment_id; END IF;
    IF TG_OP <> 'DELETE' THEN new_id := NEW.deployment_id; END IF;
  END IF;
  IF EXISTS (
    SELECT 1 FROM deployment d
    WHERE d.id IN (old_id, new_id)
      AND d.verification_status = 'verified'
      AND NOT EXISTS (SELECT 1 FROM evidence e WHERE e.deployment_id = d.id)
  ) THEN
    RAISE EXCEPTION 'Verified deployment requires at least one evidence URL';
  END IF;
  RETURN NULL;
END;
$$;
CREATE CONSTRAINT TRIGGER deployment_verified_evidence
  AFTER INSERT OR UPDATE ON deployment
  DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW EXECUTE FUNCTION enforce_verified_evidence();
CREATE CONSTRAINT TRIGGER evidence_verified_deployment
  AFTER INSERT OR UPDATE OR DELETE ON evidence
  DEFERRABLE INITIALLY DEFERRED
  FOR EACH ROW EXECUTE FUNCTION enforce_verified_evidence();
CREATE TRIGGER evidence_no_truncate
  BEFORE TRUNCATE ON evidence
  FOR EACH STATEMENT EXECUTE FUNCTION reject_history_mutation();

